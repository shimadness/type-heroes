export function Legal({ onBack, initialTab = "terms" }: Props) {
  const [tab, setTab] = useState<Tab>(initialTab);

  return (
    <div className="screen legal-screen center">
      <div className="diff-row">
        {TABS.map((t) => (
          <button
            key={t.id}
            className={`diff-btn ${tab === t.id ? "sel" : ""}`}
            onClick={() => setTab(t.id)}
          >
            {t.label}
          </button>
        ))}
      </div>

      <div className="legal-body">
        <h2>{tab === "terms" ? "利用規約" : "プライバシーポリシー"}</h2>
        <div className="legal-updated">最終更新日: {LEGAL_UPDATED}</div>
        {tab === "terms" ? <Terms /> : <Privacy />}
      </div>

      <button className="btn" onClick={onBack}>
        タイトルへもどる
      </button>
    </div>
  );
}
