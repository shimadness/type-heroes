const rand = <T,>(arr: T[]): T => arr[Math.floor(Math.random() * arr.length)];

/** 指定ジャンル・難易度からランダムに1語引く */
export function pickWord(genre: GenreId, diff: Difficulty): WordEntry {
  return rand(WORD_BANK[genre][diff]);
}

export function pickDefense(): WordEntry {
  return rand(DEFENSE_WORDS);
}
export function pickRevive(): WordEntry {
  return rand(REVIVE_WORDS);
}
export function pickUnison(): WordEntry {
  return rand(UNISON_WORDS);
}
export function randomGenres(n: number): Genre[] {
  const pool = [...GENRES];
  const out: Genre[] = [];
  while (out.length < n && pool.length > 0) {
    out.push(pool.splice(Math.floor(Math.random() * pool.length), 1)[0]);
  }
  return out;
}
